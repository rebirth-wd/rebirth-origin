// Regenerates docs/journey/TIMING.md from src/components/sections/spacejourney/timing.ts.
//   node docs/journey/tools/timing-doc.mjs
// (Node ≥ 22.18 imports the .ts file directly; on older Node run it with --experimental-strip-types.)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../../..');
const { TIMING, transitionLength } = await import(path.join(repo, 'src/components/sections/spacejourney/timing.ts'));

const f = (n) => n.toFixed(2);
const table = (name, beats, mobile) => {
  const rows = Object.entries(beats).sort(([, a], [, b]) => a.start - b.start || a.dur - b.dur);
  const out = [
    '| key | start (s) | duration (s) | end (s) | ease | what happens |',
    '|---|---:|---:|---:|---|---|',
  ];
  for (const [k, b] of rows) {
    out.push(`| \`${name}.${k}\` | ${f(b.start)} | ${b.dur ? f(b.dur) : '—'} | ${f(b.start + b.dur)} | \`${b.ease}\` | ${b.what} |`);
  }
  const over = Object.entries(mobile);
  out.push('', over.length
    ? `Phones (≤ 767px) override: ${over.map(([k, v]) => `\`${name}.${k}\` → ${JSON.stringify(v)}`).join('; ')}.`
    : 'Phones (≤ 767px): same timings as desktop (no overrides in `TIMING.mobile`).');
  return out.join('\n');
};

const LA = transitionLength(TIMING.A), LB = transitionLength(TIMING.B);
const g = TIMING.global;
const md = `# Space Journey timing

<!-- GENERATED by docs/journey/tools/timing-doc.mjs from src/components/sections/spacejourney/timing.ts. Do not edit by
hand: change timing.ts and run \`node docs/journey/tools/timing-doc.mjs\`. -->

The page rests only at three stops: **hero → section2 → appdesign**. The first scroll intent at a stop (wheel,
trackpad, swipe, ArrowDown / PageDown / Space / End, or the reverse keys) starts a transition, which then plays by time
to the end on its own. Input during a transition is ignored. Going back plays the same timeline in reverse.

All times are seconds from the start of **that** transition. Rows are sorted by start time.

| transition | from → to | length | notes |
|---|---|---:|---|
| **A** | hero → section2 | ${f(LA)} s | hands touch at ${f(TIMING.A.handsTouch.start + TIMING.A.handsTouch.dur)} s, screen fully smoke at ${f(TIMING.A.cameraRush.start + TIMING.A.cameraRush.dur)} s |
| **B** | section2 → appdesign | ${f(LB)} s | flash peak (\`showcase.play()\`) at ${f(TIMING.B.flashPeak.start)} s |
| A reversed | section2 → hero | ${f(LA / g.reverseSpeed)} s | same timeline backwards × ${g.reverseSpeed} |
| B reversed | appdesign → section2 | ${f(LB / g.reverseSpeed)} s | same timeline backwards × ${g.reverseSpeed}; \`showcase.reset()\` at the flash |

## Global knobs (\`TIMING.global\`)

| key | value | meaning |
|---|---:|---|
| \`global.reverseSpeed\` | ${g.reverseSpeed} | reverse transitions play this many times faster than forwards (1 = same speed) |
| \`global.arrivalCooldown\` | ${f(g.arrivalCooldown)} s | after arriving at a stop, intents in this window are ignored (and use up their gesture) |
| \`global.inputQuietGap\` | ${f(g.inputQuietGap)} s | input silence that separates two gestures; a trackpad fling + its inertia is one gesture and can start only one transition |
| \`global.tolerance\` | ${g.tolerance} px | wheel / finger travel before an intent counts (GSAP Observer) |
| \`global.flashHold\` | ${f(g.flashHold)} s | screen stays white after the flash peak (= \`B.whiteHold\` duration) |
| \`global.flashFade\` | ${f(g.flashFade)} s | the white fades off the phone showcase (= \`B.whiteFade\` duration) |

## Transition A: hero → section2 (${f(LA)} s)

${table('A', TIMING.A, TIMING.mobile.A)}

## Transition B: section2 → appdesign (${f(LB)} s)

${table('B', TIMING.B, TIMING.mobile.B)}

The showcase's own automatic sequence (phone feed, heart tap, side phones, loops) starts at \`B.flashPeak\` and keeps
running after arrival; its timings are in \`src/components/sections/phoneshowcase/controller.ts\` (\`T\`).

## How to change a timing

1. Open \`src/components/sections/spacejourney/timing.ts\` and edit the beat's \`start\`, \`dur\` or \`ease\`
   (any [GSAP ease name](https://gsap.com/docs/v3/Eases)). Starts are seconds from the start of that transition.
   To lengthen a transition, also move its \`arrival\` (a beat that runs past \`arrival\` extends the transition and
   logs a console warning). The flash hold and fade are \`FLASH_HOLD\` / \`FLASH_FADE\` at the top of the file.
2. Save; the dev server reloads. Open \`/?journey=debug\` to review: the overlay shows the stop, the transition, the
   time in seconds and the beats active at that moment. **P** pauses, **[** / **]** step 0.1 s back / forward while
   paused, **R** replays the current transition, **1 / 2 / 3** jump to hero / section2 / appdesign.
3. Run \`node docs/journey/tools/timing-doc.mjs\` to regenerate this table.
4. For a phone-only change, add an override in \`TIMING.mobile\`, e.g. \`mobile: { A: { cameraRush: { dur: 0.7 } }, B: {} }\`.

Things that must stay together: \`A.handsTouch\` should end when \`A.cameraRush\` ends (hands touch = screen fully
smoke), and \`A.gradientIn\` should start then. \`A.idleFreeze\`, \`A.idleCorrection\`, \`A.cameraRush\` and
\`A.cameraCentre\` start together. \`B.flashIn\` should end at \`B.flashPeak\`, which is where \`B.whiteHold\` starts.
`;

fs.writeFileSync(path.join(repo, 'docs/journey/TIMING.md'), md);
console.log(`wrote docs/journey/TIMING.md (A ${f(LA)} s, B ${f(LB)} s)`);
